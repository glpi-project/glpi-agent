package GLPI::Agent::Event;

use strict;
use warnings;

use English qw(-no_match_vars);
use UNIVERSAL::require;

use GLPI::Agent::Logger;
use GLPI::Agent::Tools;

use constant priority   => 100;

# Supported events
# 1. init:
#  - init event are triggered when the service starts
#  - can't be triggered via http request
# 2. runnow:
#  - can be trigerred by /now http requests from agent HTTP UI or GLPI
#  - must be evaluated before partial inventory as it can use "partial" param
#  - can be used to trigger one or more tasks via task or tasks param
#  - can be delayed using delay param to provide a delay value in seconds
#  - inventory task can be forced to full by setting full param to "1" or "yes"
# 3. taskrun:
#  - can be trigerred by /now http requests or following a runnow event
#  - must be evaluated before partial inventory as it can use "partial" param
#  - task is mandatory and can only be used to trigger a planned task
#  - can be delayed using delay param to provide a delay value in seconds
#  - for inventory task:
#    - full or partial params can be to "1" or "yes"
#    - full default is 1 and has precedence other partial if the 2 are defined
# 4. partial inventory:
#  - can be trigerred by /now http requests
#  - can be requested by glpi-inventory run via --partial parameter
# 5. maintenance: internal event to trigger maintenance needs
#  - for deploy, it cleans up storage from file parts when too old
#  - can't be triggered via http request
# 6. job:
#  - job events are created by toolbox managed inventory tasks
#  - can't be triggered via http request

# For event type tests
use constant init           => 0;
use constant runnow         => 0;
use constant taskrun        => 0;
use constant partial        => 0;
use constant maintenance    => 0;
use constant job            => 0;

# Attributes default
use constant category       => '';
use constant httpd_support  => 0;

my @subclasses;

sub new {
    my ($class, %params) = @_;

    my $self;

    # Load subclasses if still not done
    unless (@subclasses) {
        my %priority;
        my ($_classpath) = $INC{module2file(__PACKAGE__)} =~ /^(.*)\.pm$/;
        $_classpath =~ s{\\}{/}g if $OSNAME eq 'MSWin32';
        my ($_modulepath) = module2file(__PACKAGE__) =~ /^(.*)\.pm$/;
        $_modulepath =~ s{\\}{/}g if $OSNAME eq 'MSWin32';
        my $subclass_path_re = qr/$_modulepath\/(\S+)\.pm$/;
        foreach my $file (File::Glob::bsd_glob("$_classpath/*.pm")) {
            $file =~ s{\\}{/}g if $OSNAME eq 'MSWin32';
            my ($class) = $file =~ $subclass_path_re
                or next;
            my $module = __PACKAGE__ . "::" . $class;
            $module->require();
            if ($EVAL_ERROR) {
                my $logger = GLPI::Agent::Logger->new();
                $logger->debug("Failed to load $module");
                $logger->debug2("$module require error: $EVAL_ERROR");
                next;
            }
            $priority{$module} = $module->priority();
            push @subclasses, $module;
        }
        @subclasses = sort { $priority{$a} <=> $priority{$b} } keys(%priority);
    }

    # Initialize from content generated by dump_for_message if required
    %params = %{$params{from_message}} unless empty($params{from_message});

    foreach my $subclass (@subclasses) {
        $self = $subclass->new(%params);
        last if ref($self);
    }

    return unless defined($self);

    # Commonly setup target if defined
    $self->{_target} = $params{target} unless empty($params{target});

    return $self;
}

# Mandatory, event is invalid if not present
sub name {
    my ($self) = @_;
    return $self->{_name} // '';
}

# Common event attributes

sub task {
    my ($self) = @_;
    return $self->{_task} // '';
}

sub target {
    my ($self) = @_;
    return $self->{_target} // '';
}

sub params {
    my ($self) = @_;
    return $self->{_params} // {};
}

sub delay {
    my ($self) = @_;
    return $self->{_delay} // 0;
}

# Common event methods

sub get {
    my ($self, $key) = @_;
    return unless $key && ref($self->{_params}) eq "HASH";
    return $self->{_params}->{$key};
}

sub rundate {
    my ($self, $rundate) = @_;

    $self->{_rundate} = $rundate if $rundate;

    return $self->{_rundate} // 0;
}

sub dump_as_string {
    my ($self) = @_;
    my $dump = $self->dump_for_message();
    return join("&", map { $_."=".(ref($dump->{$_}) || $dump->{$_}) } grep { ! ref($dump->{$_}) } keys(%{$dump}));
}

sub dump_for_message {
    my ($self) = @_;
    my $dump = {};
    foreach my $key (keys(%{$self})) {
        my ($name) = $key =~ /^_?(.*)$/;
        $dump->{$name} = $self->{$key} // "";
    }
    return $dump;
}

1;
